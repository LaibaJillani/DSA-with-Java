// A Program for Java variables 
public class Variables {
    public static void main(String[] args) {
        String firstname = "Laiba "; // a string created for storing firstname 
        String lastname = "Jillani"; // a string created for storing lastname 
        String fullname;
        fullname = firstname + lastname;
        System.out.println(fullname); // for printing fullname

        final int myAge = 20; // final keyword used so that myAge will have a fix value
        System.out.println(myAge);

    }
}