public class DataTypes {
    public static void main(String[] args) {
        // Primitive data types
    int number = 456;
    long number2 = 25678954367656L;
    boolean result = true;
    char character = '$';
    float number3 = 56.9f;
    double number4 = 3425.7654;

        System.out.println("Integer is: " + number);
        System.out.println("Long Integer is: " + number2);
        System.out.println("Choice is: " + result);
        System.out.println("Currency is: " + character);
        System.out.println("Float Number is: " + number3);
        System.out.println("Double decimal Number is: " + number4);

        // Non Primitive data type
        String name = "Hi! My name is Laiba.";
        System.out.println(name);
    }
}