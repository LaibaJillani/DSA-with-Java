// A Java program for printing Hello World
public class Demo { // class name should be same as file name

    public static void main(String[] args) { // main() method is required in every Java program.
        
        System.out.println("Hello World!");
        /*print() can also be used for printing output, but it doesn't print a new line.
         Code statement ends with a semicolon.*/

        System.out.println("I'm learning Java Programming."); // The text you need as output should be closed in double quotes.

        System.out.println(20); // The numbers you need as output doesn't need to be closed in double quotes.
    }
}